const catalogRows = [
  ...COMMON_CATALOG,
  ...AUTH_CATALOG,
  ...BOARD_CATALOG,
  ...BOARDS_CATALOG,
  ...SETTINGS_CATALOG,
  ...AI_PAIRING_CATALOG,
  ...AI_CONNECTIONS_CATALOG,
  ...CODEX_CATALOG,
] as const;
const catalogRowsByKey = new Map(catalogRows.map((row) => [row[0], row] as const));
if (catalogRowsByKey.size !== catalogRows.length)
  throw new TypeError('catalog modules contain duplicate keys');
const BASE_CATALOG = BASE_CATALOG_ORDER.map((key) => {
  const row = catalogRowsByKey.get(key);
  if (row === undefined) throw new TypeError(`catalog module is missing ${key}`);
  return row;
});

const CATALOG = [...BASE_CATALOG, ...INTERFACE_CATALOG, ...PRESENTATION_CATALOG] as const;

export type MessageKey = (typeof CATALOG)[number][0];
type MessageDictionary = Readonly<Record<MessageKey, string>>;

const localeIndexes: Readonly<Record<Locale, number>> = {
  en: 1,
  ko: 2,
  ja: 3,
  'zh-CN': 4,
  'zh-TW': 5,
  es: 6,
  fr: 7,
  de: 8,
  'pt-BR': 9,
  ru: 10,
};

export const MESSAGES = Object.fromEntries(
  SUPPORTED_LOCALES.map((locale) => [
    locale,
    Object.fromEntries(CATALOG.map((row) => [row[0], row[localeIndexes[locale]]])),
  ]),
) as Record<Locale, MessageDictionary>;

export const messageKeys = (): MessageKey[] => CATALOG.map((row) => row[0]);
